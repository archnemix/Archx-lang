//! Lexical token definitions and human-readable token descriptions for parser diagnostics.

use crate::diag::Span;

#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    // Keywords
    Func,
    Struct,
    Region,
    With,
    Pass,
    Assert,
    Let,
    Return,
    If,
    Elif,
    Else,
    While,
    For,
    In,
    Break,
    Continue,
    And,
    Or,
    Not,
    Lambda,
    NoneLit,

    // Literals
    Ident(String),
    Int(i64),
    Float(f64),
    Str(String),
    FStr(Vec<(bool, String)>),
    Bool(bool),

    // Punctuation
    Colon,
    Semicolon,
    Pipe,
    Arrow,
    Dot,
    DotDot,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Plus,
    Minus,
    Star,
    StarStar,
    Slash,
    SlashSlash,
    Percent,
    Amp,
    Caret,
    Tilde,
    Shl,
    Shr,
    Eq,
    PlusEq,
    MinusEq,
    StarEq,
    StarStarEq,
    SlashEq,
    SlashSlashEq,
    PercentEq,
    EqEq,
    NotEq,
    Lt,
    Gt,
    Le,
    Ge,

    // Layout
    Newline,
    Indent,
    Dedent,
    Eof,
}

impl TokenKind {
    pub fn describe(&self) -> String {
        match self {
            TokenKind::Func => "`def` / `func`".to_string(),
            TokenKind::Struct => "`class` / `struct`".to_string(),
            TokenKind::Region => "`region`".to_string(),
            TokenKind::With => "`with`".to_string(),
            TokenKind::Pass => "`pass`".to_string(),
            TokenKind::Assert => "`assert`".to_string(),
            TokenKind::Let => "`let`".to_string(),
            TokenKind::Return => "`return`".to_string(),
            TokenKind::If => "`if`".to_string(),
            TokenKind::Elif => "`elif`".to_string(),
            TokenKind::Else => "`else`".to_string(),
            TokenKind::While => "`while`".to_string(),
            TokenKind::For => "`for`".to_string(),
            TokenKind::In => "`in`".to_string(),
            TokenKind::Break => "`break`".to_string(),
            TokenKind::Continue => "`continue`".to_string(),
            TokenKind::And => "`and`".to_string(),
            TokenKind::Or => "`or`".to_string(),
            TokenKind::Not => "`not`".to_string(),
            TokenKind::Lambda => "`lambda`".to_string(),
            TokenKind::NoneLit => "`None`".to_string(),
            TokenKind::Ident(name) => format!("identifier `{name}`"),
            TokenKind::Int(n) => format!("integer `{n}`"),
            TokenKind::Float(x) => format!("float `{x}`"),
            TokenKind::Str(_) => "string literal".to_string(),
            TokenKind::FStr(_) => "f-string literal".to_string(),
            TokenKind::Bool(value) => format!("boolean `{value}`"),
            TokenKind::Colon => "`:`".to_string(),
            TokenKind::Semicolon => "`;`".to_string(),
            TokenKind::Pipe => "`|`".to_string(),
            TokenKind::Amp => "`&`".to_string(),
            TokenKind::Caret => "`^`".to_string(),
            TokenKind::Tilde => "`~`".to_string(),
            TokenKind::Shl => "`<<`".to_string(),
            TokenKind::Shr => "`>>`".to_string(),
            TokenKind::Arrow => "`->`".to_string(),
            TokenKind::Dot => "`.`".to_string(),
            TokenKind::DotDot => "`..`".to_string(),
            TokenKind::LParen => "`(`".to_string(),
            TokenKind::RParen => "`)`".to_string(),
            TokenKind::LBracket => "`[`".to_string(),
            TokenKind::RBracket => "`]`".to_string(),
            TokenKind::LBrace => "`{`".to_string(),
            TokenKind::RBrace => "`}`".to_string(),
            TokenKind::Comma => "`,`".to_string(),
            TokenKind::Plus => "`+`".to_string(),
            TokenKind::Minus => "`-`".to_string(),
            TokenKind::Star => "`*`".to_string(),
            TokenKind::StarStar => "`**`".to_string(),
            TokenKind::Slash => "`/`".to_string(),
            TokenKind::SlashSlash => "`//`".to_string(),
            TokenKind::Percent => "`%`".to_string(),
            TokenKind::Eq => "`=`".to_string(),
            TokenKind::PlusEq => "`+=`".to_string(),
            TokenKind::MinusEq => "`-=`".to_string(),
            TokenKind::StarEq => "`*=`".to_string(),
            TokenKind::StarStarEq => "`**=`".to_string(),
            TokenKind::SlashEq => "`/=`".to_string(),
            TokenKind::SlashSlashEq => "`//=`".to_string(),
            TokenKind::PercentEq => "`%=`".to_string(),
            TokenKind::EqEq => "`==`".to_string(),
            TokenKind::NotEq => "`!=`".to_string(),
            TokenKind::Lt => "`<`".to_string(),
            TokenKind::Gt => "`>`".to_string(),
            TokenKind::Le => "`<=`".to_string(),
            TokenKind::Ge => "`>=`".to_string(),
            TokenKind::Newline => "a newline".to_string(),
            TokenKind::Indent => "an indent".to_string(),
            TokenKind::Dedent => "a dedent".to_string(),
            TokenKind::Eof => "end of file".to_string(),
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, span: Span) -> Self {
        Self { kind, span }
    }
}
