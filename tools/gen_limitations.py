#!/usr/bin/env python3
"""Generates `docs/LIMITATIONS.md` from the conformance probes (AX-008).

The limitations list is not written by hand. Every entry comes from a probe in `tests/conformance/`
that carries `# conformance: xfail <reason>`, so the document cannot drift from what the harness
actually measures: a gap that gets fixed turns into an unexpected pass (which fails CI until the
marker is removed), and the doc is regenerated from the same markers.

`--check` fails if the committed document is stale, which is what CI runs.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROBES = ROOT / "tests" / "conformance"
DOC = ROOT / "docs" / "LIMITATIONS.md"
HEADER = "<!-- Generated by tools/gen_limitations.py"

XFIL = re.compile(r"^# conformance: xfail (.+)$")


def collect() -> tuple[list[tuple[str, str, str]], int]:
    """Returns `(gaps, total)` where each gap is `(probe, area, reason)`."""
    gaps = []
    total = 0
    for probe in sorted(PROBES.glob("*.py")):
        total += 1
        source = probe.read_text().splitlines()
        reason = None
        for line in source[:3]:
            match = XFIL.match(line.strip())
            if match:
                reason = match.group(1).strip()
                break
        if reason is None:
            continue
        # The probe name encodes its area: `007-str_split_join` -> `str`.
        area = probe.stem.split("-", 1)[1].split("_")[0]
        gaps.append((probe.stem, area, reason))
    return gaps, total


def render(gaps: list[tuple[str, str, str]], total: int) -> str:
    by_area: dict[str, list[tuple[str, str]]] = {}
    for name, area, reason in gaps:
        by_area.setdefault(area, []).append((name, reason))

    out = [f"{HEADER}: regenerate with `python3 tools/gen_limitations.py`. -->", ""]
    out.append("# Known limitations")
    out.append("")
    out.append(
        "Every claim here is measured, not remembered. `tests/conformance/` holds "
        f"{total} programs that are simultaneously legal Python and legal Archx; each is executed by "
        "`python3` and compiled by `archx`, and stdout is compared byte for byte "
        "(`cargo test --test conformance`)."
    )
    out.append("")
    out.append(
        f"{len(gaps)} of those {total} programs are known **not** to reproduce CPython yet. Each one is "
        "marked `# conformance: xfail <reason>` in its own source file, and this document is generated "
        "from those markers."
    )
    out.append("")
    out.append(
        "A gap is removed from this list only by making the probe pass, which turns it into an "
        "*unexpected pass* and fails CI until the marker is deleted. A new gap cannot be added by "
        "editing this file: it needs a probe and a reason."
    )
    out.append("")
    out.append("## Not implemented")
    out.append("")
    out.append(
        "These constructs are rejected at compile time. Rejection is a documented limitation, not a "
        "wrong answer: no program in this list produces output that differs from CPython silently."
    )
    out.append("")
    out.append("| Area | Probe | What is missing |")
    out.append("|---|---|---|")
    for area in sorted(by_area):
        for name, reason in by_area[area]:
            out.append(f"| `{area}` | `{name}` | {reason} |")
    out.append("")
    out.append("## Divergences that are deliberate")
    out.append("")
    out.append(
        "Two behaviours differ from CPython *by contract* rather than by omission. Both are checked by "
        "the suite, and both are ordinary values in a **native** module while a **compat** module must "
        "match CPython:"
    )
    out.append("")
    out.append(
        "* **`int` is a trapping `i64`.** An operation that cannot be represented raises "
        "`archx runtime panic: integer overflow` (exit 101) instead of continuing with an arbitrary-precision "
        "value. `9223372036854775807 + 1`, `2 ** 63`, `abs(-9223372036854775808)` and `3037000500 * 3037000500` "
        "all trap; the constant folder obeys the same rule."
    )
    out.append(
        "* **Errors trap instead of raising.** A compat module that divides by zero, indexes past the end "
        "of a list or reads a missing dict key exits 101 with a diagnostic; it does not raise a Python "
        "exception, because exceptions are not implemented."
    )
    out.append("")
    out.append("## Running on another platform")
    out.append("")
    out.append(
        "The leak gate (`ci/leakcheck.c`, `-Wl,--wrap=malloc`) is a GNU `ld`/`lld` feature, so it runs on "
        "Linux only; macOS `ld64` rejects `--wrap` and MSVC's linker accepts it without wrapping anything. "
        "The ASan+LSan step is the cross-platform check and runs everywhere."
    )
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed doc is stale")
    args = parser.parse_args()

    expected = render(*collect())
    current = DOC.read_text() if DOC.is_file() else ""

    if args.check:
        if current == expected:
            print("docs/LIMITATIONS.md matches the conformance probes")
            return 0
        print("docs/LIMITATIONS.md is stale; run python3 tools/gen_limitations.py", file=sys.stderr)
        return 1

    if current != expected:
        DOC.write_text(expected)
        print("docs/LIMITATIONS.md regenerated")
    else:
        print("docs/LIMITATIONS.md already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
