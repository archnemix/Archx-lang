#!/usr/bin/env python3
"""Generates `docs/DIALECTS.md` from `archx --dialect-matrix` (AX-016).

The divergence matrix lives in `src/dialect_rules.rs`. This script renders the reference from the
built compiler, so the table a reader sees is the table the backend obeys — including which rows are
enforced today and which are still the intended contract. `--check` fails when the committed file is
stale, which is what CI runs.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "DIALECTS.md"

INTRO = """\
<!-- Generated by `python3 tools/gen_dialect_matrix.py`; CI fails if this file drifts (AX-016). -->

# The two dialects

Every module declares which contract it is compiled against, on its first line:

```python
# archx: dialect=compat, version=1    # or dialect=native
```

The choice cannot be inferred from syntax, because the same source text is legal in both and means
different things: `1 << 64` is `0` under native and `18446744073709551616` under compat. So the
compiler refuses to guess (`E0100`), and `--dialect` can override a directive that is present but
never substitute for one that is missing.

| | `dialect=compat` | `dialect=native` |
|---|---|---|
| Promise | byte-identical stdout to CPython 3.12+ | documented Archx semantics |
| `int` | trapping `i64`, like native | trapping `i64` |
| Intended for | porting Python unchanged, verifying against CPython | new programs, systems work, performance |

Both contracts are *safe* in the same sense: neither wraps silently, both bounds-check, both are
leak-free under ASan/LSan. What differs is observable behaviour — spelling, indexing units, and how a
runtime failure is reported.

## How a divergence is decided

All of them live in one table, `ROWS` in `src/dialect_rules.rs`. Nothing in the backend tests the
dialect enum directly: a consumer asks the table for a row's value. That is why `print(True)` and an
f-string cannot disagree, and why this document is generated from the same rows the compiler reads.

A row marked **planned** is part of the intended contract but not implemented yet; it is also listed in
[`LIMITATIONS.md`](LIMITATIONS.md). A row marked **enforced** is implemented and covered by a test.

## The matrix

```text
"""


def binary() -> Path:
    override = os.environ.get("ARCHX_BIN")
    if override:
        return Path(override)
    for profile in ("release", "debug"):
        candidate = ROOT / "target" / profile / ("archx.exe" if os.name == "nt" else "archx")
        if candidate.exists():
            return candidate
    raise SystemExit("build the compiler first (`cargo build --release`) or set ARCHX_BIN")


def render() -> str:
    listing = subprocess.run(
        [str(binary()), "--dialect-matrix"], capture_output=True, text=True, check=True
    ).stdout
    # Drop the CLI's own title lines; the document supplies its own framing.
    lines = [
        line
        for line in listing.splitlines()
        if not line.startswith(("Dialect divergence matrix", "Each row is one decision"))
    ]
    body = "\n".join(lines).strip("\n")
    footer = """\
```

## Adding a divergence

1. Add a `Rule` variant and a `ROWS` entry in `src/dialect_rules.rs`, with `enforced: false` until the
   backend honours it.
2. Read it through `dialect_rules::value(rule, dialect)` at the call site — never
   `if dialect == Dialect::Compat`, which is how the two spellings drift apart.
3. Regenerate this document (`python3 tools/gen_dialect_matrix.py`) and the tracker.

`tests/cli.rs` asserts that `--dialect-matrix` reports a row as enforced only when a caller reads it,
so the flag cannot be flipped to make the docs look finished.
"""
    return INTRO + body + "\n" + footer


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed doc is stale")
    args = parser.parse_args()

    expected = render()
    current = DOC.read_text() if DOC.is_file() else ""

    if args.check:
        if current == expected:
            print("docs/DIALECTS.md matches the compiler's divergence matrix")
            return 0
        print("docs/DIALECTS.md is stale; run python3 tools/gen_dialect_matrix.py", file=sys.stderr)
        return 1

    if current != expected:
        DOC.write_text(expected)
        print("docs/DIALECTS.md regenerated")
    else:
        print("docs/DIALECTS.md already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
