#!/usr/bin/env python3
"""Generate the v1.0 work-order checklist from the backlog document.

The backlog (`docs/backlog/Archx-v1-backlog.md`) is the single source of truth. This script parses
its work orders and emits `docs/V1_Tracker.md`, merging in the completion state recorded in
`docs/backlog/status.json`. Generating the checklist means a work order can never be silently
dropped, renumbered, or paraphrased away from the document.

Usage:
    python3 tools/gen_tracker.py          # rewrite docs/V1_Tracker.md
    python3 tools/gen_tracker.py --check  # exit 1 if out of date (CI use)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKLOG = ROOT / "docs/backlog/Archx-v1-backlog.md"
STATUS = ROOT / "docs/backlog/status.json"
OUTPUT = ROOT / "docs/V1_Tracker.md"

ORDER = [f"AX-{n:03d}" for n in range(1, 129)]

PHASE_TEXT = {
    "P0": "Trust the current build",
    "P1": "Make the two syntaxes explicit",
    "P2": "Modules, packages, and real programs",
    "P3": "Ownership, lifetimes, and exhaustive checking",
    "P4": "Compatibility depth (CPython parity)",
    "P5": "Tooling and editor experience",
    "P6": "Ecosystem (packages, stdlib, FFI)",
    "P7": "Performance program",
    "P8": "Release engineering and governance",
}

MARK = {"done": "x", "partial": "~", "blocked": "!", "todo": " "}

KNOWN_FIELDS = {
    "phase", "area", "priority", "depends", "effort", "risk", "build", "files", "acceptance",
}
FIELD_RE = re.compile(r"^- \*\*(?P<key>[A-Za-z]+):\*\*\s*(?P<value>.*)$")
# A field line packs several pairs: "Phase: P0 · Area: Runtime · Priority: P0".
PAIR_RE = re.compile(r"(?P<key>\w+)\s*:\s*(?P<value>.*?)(?=\s*·\s*\w+\s*:|$)", re.S)


def split_pairs(value: str) -> list[tuple[str, str]]:
    """Split `A: 1 · B: 2` into [(a, 1), (b, 2)]."""
    return [
        (m.group("key").lower(), m.group("value").strip().rstrip("."))
        for m in PAIR_RE.finditer(value)
    ]


def parse_backlog() -> tuple[dict[str, dict], list[tuple[str, str]]]:
    """Return {id: fields} and the ordered [(phase, id)] layout, straight from the document."""
    items: dict[str, dict] = {}
    order: list[tuple[str, str]] = []
    phase = "P0"
    current: dict | None = None

    for raw in BACKLOG.read_text().splitlines():
        line = raw.rstrip()
        if m := re.match(r"^### (P\d) — ", line):
            phase = m.group(1)
            continue
        if m := re.match(r"^#### (AX-\d{3}) — (?P<title>.+)$", line):
            current = {
                "id": m.group(1),
                "title": m.group("title").strip(),
                "phase": phase,
                "area": "",
                "priority": phase,
            }
            items[m.group(1)] = current
            order.append((phase, m.group(1)))
            continue
        if current is None or not (m := FIELD_RE.match(line)):
            continue
        # Drop the bold markers before pair-splitting: `**Area:**` would otherwise hide the key.
        for key, val in split_pairs(m.group("value").replace("**", "")):
            if key in KNOWN_FIELDS:
                current[key] = val
    return items, order


def main() -> int:
    items, order = parse_backlog()
    status = json.loads(STATUS.read_text()) if STATUS.exists() else {}

    missing = [i for i in ORDER if i not in items]
    if missing:
        print(f"error: backlog is missing work orders: {', '.join(missing)}", file=sys.stderr)
        return 1
    extra = sorted(set(items) - set(ORDER))
    if extra:
        print(f"error: backlog has unknown work orders: {', '.join(extra)}", file=sys.stderr)
        return 1

    by_phase: dict[str, list[str]] = {}
    for phase, ident in order:
        by_phase.setdefault(phase, []).append(ident)

    counts = {"done": 0, "partial": 0, "blocked": 0, "todo": 0}
    for ident in ORDER:
        state = status.get(ident, {}).get("state", "todo")
        counts[state] = counts.get(state, 0) + 1

    out: list[str] = []
    out.append("# Archx v1.0 — Work Order Tracker")
    out.append("")
    out.append("<!-- GENERATED by tools/gen_tracker.py from docs/backlog/Archx-v1-backlog.md. -->")
    out.append("<!-- Edit docs/backlog/status.json (state) or the backlog (wording), never this file. -->")
    out.append("")
    out.append(
        "All 128 work orders in the document's own words. Ordering is mandatory: "
        "**P0 → P1 → P2 → (P3 ∥ P4) → P5 → P6 → P7 → P8** — P3 must not start before P0 and P1 "
        "are green, because adding features on unchecked overflow, leaks and an ambiguous "
        "two-syntax frontend multiplies bugs."
    )
    out.append("")
    out.append("`[x]` done and verified · `[~]` in progress · `[ ]` not started · `[!]` blocked")
    out.append("")
    out.append("## Progress")
    out.append("")
    out.append(
        f"**{counts['done']} / {len(ORDER)}** complete · {counts['partial']} in progress · "
        f"{counts['blocked']} blocked · {counts['todo']} not started"
    )
    out.append("")

    for phase in sorted(by_phase):
        ids = by_phase[phase]
        done = sum(1 for i in ids if status.get(i, {}).get("state") == "done")
        out.append(f"## {phase} — {PHASE_TEXT.get(phase, '')} ({done}/{len(ids)})")
        out.append("")
        out.append(
            "| # | Work order | Phase | Area | Priority | Depends | Effort | Risk | Status | Notes |"
        )
        out.append("|---|---|---|---|---|---|---|---|---|---|")
        for ident in ids:
            it = items[ident]
            st = status.get(ident, {})
            state = st.get("state", "todo")
            notes = st.get("note", "").replace("|", "\\|")
            out.append(
                f"| {ident} | {it['title'].replace('|', '/')} | {it['phase']} | {it.get('area','')} | "
                f"{it.get('priority','')} | {it.get('depends','—')} | {it.get('effort','')} | "
                f"{it.get('risk','')} | `[{MARK.get(state, ' ')}]` | {notes} |"
            )
        out.append("")

    out.append("## Verified baseline")
    out.append("")
    out.append("Re-measure after every work order.")
    out.append("")
    out.append("| Check | Result |")
    out.append("|---|---|")
    out.append("| `cargo build --release` | clean, 13 pre-existing warnings (AX-004 target) |")
    out.append("| `cargo test --release` | 42 unit + 38 CLI = **80 pass, 0 fail** |")
    out.append("| CI run 45999706770 | **all 4 jobs green** (Linux, macOS, Windows, records) |")
    out.append("| ASan+LSan `ci/logs/asan_lsan.log` | **11/11 CLEAN** |")
    out.append("| Leak gate `ci/logs/leakcheck.log` | **12/12 clean** (Linux only — see note) |")
    out.append("| `benchmarks/pipelines.archx.lang` vs CPython 3.12 | byte-identical `5333140919445` |")
    out.append("| Audit baseline (94 Python probes) | 73/94 = 78 % |")
    out.append("")
    out.append("**Leak-coverage note.** Both leak checks are Linux-only: ASan does not link against")
    out.append("Archx IR on this toolchain, and `--wrap` needs GNU ld/lld (macOS `ld64` rejects it;")
    out.append("Windows MSVC ignores it and fails with LNK1120). \"Zero leaks\" is a Linux result;")
    out.append("macOS and Windows are covered for correctness by the full suite, not for leak-freedom.")
    out.append("")

    rendered = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            print("error: docs/V1_Tracker.md is out of date; run tools/gen_tracker.py", file=sys.stderr)
            return 1
        print("docs/V1_Tracker.md is up to date")
        return 0
    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(ROOT)} — {counts['done']}/{len(ORDER)} complete")
    return 0


if __name__ == "__main__":
    sys.exit(main())
