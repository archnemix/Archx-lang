#!/usr/bin/env python3
"""Generates `docs/ERROR_CODES.md` from the compiler's own `archx --explain` output (AX-011).

The registry lives in `src/error_codes.rs`. This script runs the built binary and renders the
reference from it, so the documentation cannot describe codes the compiler does not have (or omit a
code it does emit). `--check` fails if the committed file is stale, which is what CI runs.

Usage:
    python3 tools/gen_error_codes.py            # rewrite the document
    python3 tools/gen_error_codes.py --check    # fail if it is stale
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "ERROR_CODES.md"

INTRO = """\
<!-- Generated by `python3 tools/gen_error_codes.py`; CI fails if this file drifts (AX-011). -->

# Error codes

Every diagnostic Archx emits has a stable code, and every code is documented here. The source of truth
is `src/error_codes.rs`; this file is rendered from `archx --explain`, so the reference cannot describe
a compiler that does not exist.

Why codes exist at all: a message is for a person and may be reworded, but a code is for a tool. Build
systems, editors and test suites can branch on `E0402` without matching English text, and a suppression
list stays valid when a message improves.

The codes are grouped by area, and the grouping is part of the contract:

| Range | Area |
|---|---|
| `E00xx` | driver (flags, paths, toolchain) |
| `E01xx` | the dialect directive |
| `E02xx` | lexing |
| `E03xx` | parsing |
| `E04xx` | types and calls |
| `E05xx` | names |
| `E06xx` | collections |
| `E07xx` | control flow |
| `E08xx` | dialect-specific constructs |
| `E09xx` | internal — always an Archx bug |

## Shape of a diagnostic

```text
error[E0402]: type mismatch: expected `int`, found `str`
  --> demo.archx.lang:3:14
   |
 3 |     x: int = "hello"
   |              ^
```

That goes to **stderr**; a successful compilation prints nothing there.
`--message-format=json` emits one object per line instead:

```json
{"code":"E0402","severity":"error","message":"type mismatch: expected `int`, found `str`","summary":"type mismatch","file":"demo.archx.lang","line":3,"column":14,"internal":false}
```

`archx explain E0402` prints that code's entry, and `archx explain` with no argument lists the registry.
Every diagnostic a source file can trigger is checked against this list by `tests/error_codes.rs`, which
extracts the message literals from the compiler's own source and fails if any of them has no code.

## The registry
"""


def binary() -> Path:
    """The compiler to document: `ARCHX_BIN`, then a release build, then a debug build."""
    override = os.environ.get("ARCHX_BIN")
    if override:
        return Path(override)
    for profile in ("release", "debug"):
        candidate = ROOT / "target" / profile / ("archx.exe" if os.name == "nt" else "archx")
        if candidate.exists():
            return candidate
    raise SystemExit("build the compiler first (`cargo build --release`) or set ARCHX_BIN")


def render() -> str:
    listing = subprocess.run(
        [str(binary()), "--explain"], capture_output=True, text=True, check=True
    ).stdout
    # `--explain` prints a title, a hint, then the registry; keep the registry verbatim so the document
    # and the CLI cannot disagree. Both header lines are dropped by prefix, not by position.
    lines = [
        line
        for line in listing.splitlines()
        if not line.startswith(("Error codes", "Run `archx explain"))
    ]
    listing = "\n".join(lines)
    return INTRO + "\n```text\n" + listing.strip("\n") + "\n```\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed doc is stale")
    args = parser.parse_args()

    expected = render()
    current = DOC.read_text() if DOC.is_file() else ""

    if args.check:
        if current == expected:
            print("docs/ERROR_CODES.md matches the compiler's code registry")
            return 0
        print("docs/ERROR_CODES.md is stale; run python3 tools/gen_error_codes.py", file=sys.stderr)
        return 1

    if current != expected:
        DOC.write_text(expected)
        print("docs/ERROR_CODES.md regenerated")
    else:
        print("docs/ERROR_CODES.md already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
